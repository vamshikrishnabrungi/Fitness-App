async def ingest() -> Dict[str, int]:
    load_dotenv(PROJECT_ROOT / "backend" / ".env")
    client = AsyncIOMotorClient(os.environ.get("MONGO_URL", "mongodb://localhost:27017"))
    db = client[os.environ.get("DB_NAME", "test_database")]
    await ensure_database_schema(db)

    now = datetime.utcnow()
    source_doc = {
        "id": SOURCE_PACK_ID,
        "title": "Advanced Calisthenics Web Research Pack",
        "source_type": "manual_web_research",
        "domains": ["advanced_calisthenics", "bodyweight", "gymnastics_strength", "ring_skills"],
        "summary": "Curated source-backed skill and exercise knowledge for advanced calisthenics progressions, including planche, levers, rings, muscle-ups, one-arm pulling, handstand push-ups, and compression/core skills.",
        "source_count": len(SOURCES),
        "ingestion_method": INGESTION_METHOD,
        "created_at": now,
        "updated_at": now,
    }

    counts: Dict[str, int] = {}
    for collection in ("source_registry", "knowledge_sources"):
        await db[collection].replace_one({"id": SOURCE_PACK_ID}, source_doc, upsert=True)
        counts[collection] = 1

    aliases = await _canonical_id_aliases(db)
    primary_records = [record for record in EXERCISES if record["library"] == "primary"]
    variation_records = [record for record in EXERCISES if record["library"] == "variation"]
    counts["source_sections"] = await _upsert_many(db, "source_sections", _source_docs())
    counts["primary_exercise_library"] = await _upsert_many(db, "primary_exercise_library", [_catalog_doc(record, aliases) for record in primary_records])
    counts["exercise_variation_library"] = await _upsert_many(db, "exercise_variation_library", [_catalog_doc(record, aliases) for record in variation_records])
    aliases = {**aliases, **await _canonical_id_aliases(db)}
    counts["exercise_library"] = await _upsert_many(db, "exercise_library", [_raw_doc(record, aliases) for record in EXERCISES])
    counts["exercise_progression_graph"] = await _upsert_many(db, "exercise_progression_graph", _progression_docs(aliases))
    counts["programming_rules"] = await _upsert_many(db, "programming_rules", _programming_rule_docs())
    counts["workout_templates"] = await _upsert_many(db, "workout_templates", _template_docs(aliases))
    client.close()
    return counts


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Ingest source-backed advanced calisthenics web research into MongoDB.")
    return parser.parse_args()


def main() -> None:
    parse_args()
    counts = asyncio.run(ingest())
    for collection, count in counts.items():
        print(f"{collection}: {count}")


if __name__ == "__main__":
    main()
