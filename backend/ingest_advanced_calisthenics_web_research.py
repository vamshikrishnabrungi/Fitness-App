def _merge_list(existing: Any, incoming: Any) -> List[Any]:
    items: List[Any] = []
    for value in [existing, incoming]:
        if not value:
            continue
        values = value if isinstance(value, list) else [value]
        for item in values:
            if item not in items:
                items.append(item)
    return items


def _merge_doc(existing: Dict[str, Any], incoming: Dict[str, Any], now: datetime) -> Dict[str, Any]:
    merged = dict(existing)
    for key, value in incoming.items():
        if key in {"_id", "id", "created_at"}:
            continue
        if key in {
            "aliases",
            "equipment",
            "equipment_required",
            "patterns",
            "movement_patterns",
            "qualities",
            "training_qualities",
            "primary_muscles",
            "secondary_muscles",
            "coaching_cues",
            "common_errors",
            "use_when",
            "avoid_when",
            "progressions",
            "regressions",
            "source_refs",
            "sport_tags",
            "contraindications",
            "injury_flags",
            "source_book_ids",
            "alternate_ids",
        }:
            merged[key] = _merge_list(existing.get(key), value)
        elif value not in (None, "", [], {}) and existing.get(key) in (None, "", [], {}):
            merged[key] = value
    if incoming.get("summary") and incoming.get("source_book_id") == SOURCE_PACK_ID:
        merged["summary"] = incoming["summary"]
    merged["source_book_ids"] = _merge_list(merged.get("source_book_ids"), [existing.get("source_book_id"), incoming.get("source_book_id")])
    if existing.get("id") != incoming.get("id"):
        merged["alternate_ids"] = _merge_list(merged.get("alternate_ids"), incoming.get("id"))
    merged["updated_at"] = now
    return merged


async def _upsert_many(db: Any, collection_name: str, docs: Iterable[Dict[str, Any]]) -> int:
    now = datetime.utcnow()
    count = 0
    collection = db[collection_name]
    for doc in docs:
        doc = {**doc, "updated_at": now}
        doc.setdefault("created_at", now)
        if collection_name == "source_sections" and doc.get("source_book_id") == SOURCE_PACK_ID:
            await collection.replace_one({"id": doc["id"]}, doc, upsert=True)
            count += 1
            continue
        existing = await collection.find_one({"id": doc["id"]})
        if not existing and doc.get("name"):
            existing = await collection.find_one({"name": doc["name"]})
        if existing:
            merged = _merge_doc(existing, doc, now)
            await collection.replace_one({"id": existing["id"]}, merged)
        else:
            await collection.replace_one({"id": doc["id"]}, doc, upsert=True)
        count += 1
    return count


async def _canonical_id_aliases(db: Any) -> Dict[str, str]:
    aliases: Dict[str, str] = {}
    for collection_name, records in [
        ("primary_exercise_library", [record for record in EXERCISES if record["library"] == "primary"]),
        ("exercise_variation_library", [record for record in EXERCISES if record["library"] == "variation"]),
    ]:
        collection = db[collection_name]
        for record in records:
            existing = await collection.find_one({"name": record["name"]}, {"id": 1})
            if existing and existing.get("id") and existing["id"] != record["id"]:
                aliases[record["id"]] = existing["id"]
    return aliases


def _canonical_id(value: str, aliases: Dict[str, str]) -> str:
    return aliases.get(value, value)


def _remap_exercise_ids(value: Any, aliases: Dict[str, str]) -> Any:
    if isinstance(value, list):
        return [_remap_exercise_ids(item, aliases) for item in value]
    if isinstance(value, dict):
        remapped = {}
        for key, item in value.items():
            if key == "exercise_id" and isinstance(item, str):
                remapped[key] = _canonical_id(item, aliases)
            else:
                remapped[key] = _remap_exercise_ids(item, aliases)
        return remapped
    return value


